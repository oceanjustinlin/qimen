test(`表驱动：${CASES.length} 组简体 → 繁体`, () => {
  assert.ok(CASES.length >= 120, `至少 120 组，当前 ${CASES.length}`);
  for (const [simp, hant] of CASES) assert.equal(toHant(simp), hant, simp);
});

test('幂等：期望繁体再转一次不变', () => {
  for (const [, hant] of CASES) assert.equal(toHant(hant), hant, hant);
});

test('不含中文的字符串原样返回', () => {
  for (const s of ['', 'Open Door', '72', '2026-11-18 03:58', '!?…', '🔮✨', 'a/b-c']) {
    assert.equal(toHant(s), s);
  }
  assert.equal(toHant(undefined), undefined);
});

test('不传通用转换时只应用保护词表', () => {
  assert.equal(convertWithProtect('请先登录', null), '请先登入');
  assert.equal(convertWithProtect('时干', null), '時干');
});

test('splitProtected 切分', () => {
  assert.deepEqual(splitProtected(''), []);
  assert.deepEqual(splitProtected('你好'), [{ text: '你好', locked: false }]);
  const segs = splitProtected('看时干');
  assert.equal(segs.map((s) => s.text).join(''), '看时干');
  assert.ok(segs.some((s) => s.locked && s.out.includes('干')));
});

test('PROTECT 按简体长度降序，且写法与简体等长', () => {
  for (let i = 1; i < PROTECT.length; i += 1) {
    assert.ok(PROTECT[i - 1][0].length >= PROTECT[i][0].length);
  }
  for (const [simp, out] of PROTECT) {
    if (out !== null) assert.equal(out.length, simp.length, simp);
  }
});

test('保护词条里非敏感字的写法与 OpenCC 单字结果一致（保证幂等）', () => {
  const INTENTIONAL = new Set(['斗', '干', '冲', '丑', '凶', '咸', '复', '录', '账', '认']);
  for (const [simp, out] of PROTECT) {
    if (out === null) continue;
    [...simp].forEach((ch, i) => {
      if (INTENTIONAL.has(ch)) return;
      const generic = opencc(ch);
      if (generic === ch) return;
      assert.equal(out[i], generic, `${simp} 的「${ch}」应写作「${generic}」，请补进 CHAR_HANT`);
    });
  }
});
